describe("suggester: the `EOy` prompt (annex §C5.3)", () => {
  it("is the annex's fenced block, byte for byte", () => {
    const annex = readFileSync(fileURLToPath(new URL("../../../docs/superpowers/specs/2026-08-09-wave-c-grounding/waveC-grounding-bundle.md", import.meta.url)), "utf8");
    const lines = annex.split("\n");
    const start = lines.findIndex((l) => l.startsWith("[SUGGESTION MODE:"));
    expect(start).toBeGreaterThan(0);
    const end = lines.indexOf("```", start);
    expect(end).toBeGreaterThan(start);
    expect(SUGGESTION_PROMPT).toBe(lines.slice(start, end).join("\n"));
  });
  it("carries the four load-bearing clauses upstream's own wording depends on", () => {
    expect(SUGGESTION_PROMPT).toContain("[SUGGESTION MODE: Suggest what the user might naturally type next into Claude Code.]");
    expect(SUGGESTION_PROMPT).toContain('THE TEST: Would they think "I was just about to type that"?');
    expect(SUGGESTION_PROMPT).toContain("Format: 2-12 words, match the user's style. Or nothing.");
    expect(SUGGESTION_PROMPT).toContain("Reply with ONLY the suggestion, no quotes or explanation.");
  });
  it("rides LAST in the request, after the transcript tail (upstream appends it to the conversation)", () => {
    const msg = suggestionRequestMessage("user: hi\nassistant: hello");
    expect(msg.endsWith(SUGGESTION_PROMPT)).toBe(true);
    expect(msg.indexOf("user: hi")).toBeLessThan(msg.indexOf(SUGGESTION_PROMPT));
  });
  it("is generated by a Haiku-class model (spec D-C5, a recorded divergence from upstream's main-model fork)", () => {
    expect(SUGGESTER_MODEL).toBe("haiku");
  });
});

describe("suggester.formatTranscriptTail", () => {
  it("renders `role: text` lines, oldest first (probe 100c's own tail format)", () => {
    expect(formatTranscriptTail([{ role: "user", text: "fix the bug" }, { role: "assistant", text: "fixed" }]))
      .toBe("user: fix the bug\nassistant: fixed");
  });
  it("keeps only the last `maxMessages` entries", () => {
    const entries = Array.from({ length: 10 }, (_, i) => ({ role: "user" as const, text: `m${i}` }));
    expect(formatTranscriptTail(entries, { maxMessages: 3 })).toBe("user: m7\nuser: m8\nuser: m9");
  });
  it("truncates an individual message rather than shipping a whole tool-output dump", () => {
    const tail = formatTranscriptTail([{ role: "assistant", text: "x".repeat(500) }], { maxChars: 10 });
    expect(tail).toBe("assistant: xxxxxxxxxx…");
  });
});

