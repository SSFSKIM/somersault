/** A scriptable stand-in for the library `Session` the real factory builds. Records every prompt it was
 *  handed and whether it was disposed, and lets a test park a request mid-flight. */
function fakeSuggesterSessions(replies: (string | Promise<string>)[]) {
  const spawned: { prompts: string[]; disposed: number }[] = [];
  let n = 0;
  const open = (): SuggesterSession => {
    const rec = { prompts: [] as string[], disposed: 0 };
    spawned.push(rec);
    return {
      async submit(prompt: string) { rec.prompts.push(prompt); return { result: await replies[n++] }; },
      async dispose() { rec.disposed++; },
    };
  };
  return { open, spawned };
}

describe("suggester.createSuggester — one warm session per REPL (spec EP-C5 lifecycle)", () => {
  it("spawns LAZILY — constructing it opens nothing", () => {
    const { open, spawned } = fakeSuggesterSessions([]);
    createSuggester({ openSession: open });
    expect(spawned).toHaveLength(0);
  });

  it("reuses ONE session across requests and applies the post-filter inside", async () => {
    const { open, spawned } = fakeSuggesterSessions(["run the tests", "<suggestion>commit this</suggestion>", "thanks, looks good"]);
    const s = createSuggester({ openSession: open });
    expect(await s.request({ transcriptTail: "user: a\nassistant: b" })).toBe("run the tests");
    expect(await s.request({ transcriptTail: "user: c\nassistant: d" })).toBe("commit this");
    expect(await s.request({ transcriptTail: "user: e\nassistant: f" })).toBeNull();   // evaluative → filtered
    expect(spawned).toHaveLength(1);
    expect(spawned[0].prompts).toHaveLength(3);
    expect(spawned[0].prompts[0]).toBe(suggestionRequestMessage("user: a\nassistant: b"));
  });

  it("`abort()` discards a suggestion that lands after the keystroke (`scd`, L235125)", async () => {
    let release!: (v: string) => void;
    const { open } = fakeSuggesterSessions([new Promise<string>((r) => { release = r; })]);
    const s = createSuggester({ openSession: open });
    const p = s.request({ transcriptTail: "tail" });
    s.abort();
    release("run the tests");
    expect(await p).toBeNull();
  });

  it("`retire()` disposes the session and the NEXT request spawns a fresh one (the replaceDocument boundary)", async () => {
    const { open, spawned } = fakeSuggesterSessions(["run the tests", "commit this"]);
    const s = createSuggester({ openSession: open });
    expect(await s.request({ transcriptTail: "a" })).toBe("run the tests");
    s.retire();
    expect(spawned[0].disposed).toBe(1);
    expect(await s.request({ transcriptTail: "b" })).toBe("commit this");
    expect(spawned).toHaveLength(2);
    expect(spawned[1].prompts).toHaveLength(1);
  });

  it("`retire()` also drops a request still in flight — no cross-conversation leak into the composer", async () => {
    let release!: (v: string) => void;
    const { open } = fakeSuggesterSessions([new Promise<string>((r) => { release = r; }), "commit this"]);
    const s = createSuggester({ openSession: open });
    const p = s.request({ transcriptTail: "old conversation" });
    s.retire();
    release("run the tests");
    expect(await p).toBeNull();
  });

  it("a second request supersedes the first, exactly as upstream's controller swap does", async () => {
    let release!: (v: string) => void;
    const { open } = fakeSuggesterSessions([new Promise<string>((r) => { release = r; }), "commit this"]);
    const s = createSuggester({ openSession: open });
    const first = s.request({ transcriptTail: "a" });
    const second = s.request({ transcriptTail: "b" });
    release("run the tests");
    expect(await first).toBeNull();
    expect(await second).toBe("commit this");
  });

  it("a session that throws yields null and does not wedge the next request", async () => {
    const spawned: string[] = [];
    let calls = 0;
    const open = (): SuggesterSession => {
      spawned.push("open");
      return {
        async submit() { if (calls++ === 0) throw new Error("engine died"); return { result: "run the tests" }; },
        async dispose() {},
      };
    };
    const s = createSuggester({ openSession: open });
    expect(await s.request({ transcriptTail: "a" })).toBeNull();
    expect(await s.request({ transcriptTail: "b" })).toBe("run the tests");
  });

  it("a non-string result is not a suggestion", async () => {
    const open = (): SuggesterSession => ({ async submit() { return { result: undefined }; }, async dispose() {} });
    expect(await createSuggester({ openSession: open }).request({ transcriptTail: "a" })).toBeNull();
  });
});
