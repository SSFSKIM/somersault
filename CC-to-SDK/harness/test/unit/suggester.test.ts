// One fixture per reason, in the annex table's own order — the ORDER matters as much as the rules do: a
// fixture that trips an earlier rule would silently stop testing its own.
describe("suggester.postFilterSuggestion — `AOy`'s twelve rules (annex §C5.3)", () => {
  const cases: [string, string][] = [
    ["empty", "   "],
    ["meta_text", "nothing found"],
    ["meta_wrapped", "(no idea what comes next)"],
    ["error_message", "API Error: overloaded"],
    ["prefixed_label", "Note: run the tests now"],
    ["too_few_words", "maybe"],
    ["too_many_words", "run the tests and then commit and push and deploy and check the logs"],
    ["too_long", "reconfigure everything thoroughly whenever distributed environments require substantial architectural reconsideration"],
    ["multiple_sentences", "run the tests. Then commit"],
    ["has_formatting", "run the *tests* now"],
    ["evaluative", "looks good to me"],
    ["claude_voice", "let me run the tests"],
  ];
  for (const [reason, text] of cases) {
    it(`rejects ${JSON.stringify(text.slice(0, 40))} as ${reason}`, () => {
      const v = postFilterSuggestion(text);
      expect(v.ok).toBe(false);
      expect(v.ok === false && v.reason).toBe(reason);
    });
  }
  it("catches every `meta_text` shape the table lists", () => {
    for (const t of ["nothing found.", "nothing to suggest here", "no suggestion is appropriate", "silence is better here", "staying silent", "the model stays silent", "silence"]) {
      expect(postFilterSuggestion(t)).toEqual({ ok: false, reason: "meta_text" });
    }
  });
  it("catches a bracketed wrap as well as a parenthesised one", () => {
    expect(postFilterSuggestion("[no follow-up]")).toEqual({ ok: false, reason: "meta_wrapped" });
  });
  it("catches all five error prefixes", () => {
    for (const t of ["api error: 529", "Prompt is too long for this model", "Request timed out after 60s", "Invalid API key provided", "Image was too large to send"]) {
      expect(postFilterSuggestion(t)).toEqual({ ok: false, reason: "error_message" });
    }
  });
  it("exempts a slash command and the seventeen-word allowlist from `too_few_words`", () => {
    expect(postFilterSuggestion("/compact")).toEqual({ ok: true, text: "/compact" });
    for (const t of ["yes", "yeah", "yep", "yea", "yup", "sure", "ok", "okay", "push", "commit", "deploy", "stop", "continue", "check", "exit", "quit", "no"]) {
      expect(postFilterSuggestion(t)).toEqual({ ok: true, text: t });
    }
  });
  it("rejects at exactly 100 characters and accepts at 99", () => {
    const atLength = (n: number) => `${"a".repeat(n - 4)} abc`;             // two words, exactly n characters
    expect(atLength(99)).toHaveLength(99);
    expect(postFilterSuggestion(atLength(99)).ok).toBe(true);
    expect(postFilterSuggestion(atLength(100))).toEqual({ ok: false, reason: "too_long" });
  });
  it("accepts at exactly 12 words and rejects at 13", () => {
    expect(postFilterSuggestion("a b c d e f g h i j k l").ok).toBe(true);
    expect(postFilterSuggestion("a b c d e f g h i j k l m")).toEqual({ ok: false, reason: "too_many_words" });
  });
  it("lets a real suggestion through unchanged", () => {
    for (const t of ["run the tests", "commit this", "apply the migration and run tests"]) {
      expect(postFilterSuggestion(t)).toEqual({ ok: true, text: t });
    }
  });
});

describe("suggester.suggestionSuppression — `ixs`/`yOy` MINUS `cache_cold` (annex §C5.2)", () => {
  const eligible = { assistantMessages: 2, enabled: true, mode: "default" };
  it("returns null when every gate is open", () => {
    expect(suggestionSuppression(eligible)).toBeNull();
  });
  it("`aborted` outranks everything", () => {
    expect(suggestionSuppression({ ...eligible, aborted: true, enabled: false })).toBe("aborted");
  });
  it("`early_conversation` at fewer than two assistant messages", () => {
    expect(suggestionSuppression({ ...eligible, assistantMessages: 0 })).toBe("early_conversation");
    expect(suggestionSuppression({ ...eligible, assistantMessages: 1 })).toBe("early_conversation");
    expect(suggestionSuppression({ ...eligible, assistantMessages: 2 })).toBeNull();
  });
  it("`last_response_error` on a turn that ended in error", () => {
    expect(suggestionSuppression({ ...eligible, lastTurnError: true })).toBe("last_response_error");
  });
  it("`disabled` when the setting is off — and it is checked AFTER the transcript gates", () => {
    expect(suggestionSuppression({ ...eligible, enabled: false })).toBe("disabled");
    expect(suggestionSuppression({ ...eligible, enabled: false, assistantMessages: 0 })).toBe("early_conversation");
  });
  it("`pending_permission` while a decision is parked", () => {
    expect(suggestionSuppression({ ...eligible, pendingPermission: true })).toBe("pending_permission");
  });
  it("`elicitation_active` while a question is queued", () => {
    expect(suggestionSuppression({ ...eligible, elicitationActive: true })).toBe("elicitation_active");
  });
  it("`plan_mode` in plan mode, and NOT in the other modes", () => {
    expect(suggestionSuppression({ ...eligible, mode: "plan" })).toBe("plan_mode");
    for (const mode of ["default", "acceptEdits", "auto", "bypassPermissions"]) {
      expect(suggestionSuppression({ ...eligible, mode })).toBeNull();
    }
  });
  it("`rate_limit` when the plan is not allowed to spend", () => {
    expect(suggestionSuppression({ ...eligible, rateLimited: true })).toBe("rate_limit");
  });
  it("does NOT carry `cache_cold` — a large last turn is still eligible (spec EP-C5)", () => {
    expect(suggestionSuppression({ ...eligible, lastTurnTokens: 999_999 } as never)).toBeNull();
  });
});

describe("suggester: the four-state machine (annex §C5.4)", () => {
  const generated: PromptSuggestion = { status: "generated", text: "run the tests" };
  it("`wYe`/`Bgn`: only shown/accepted are visible; every non-empty status has text", () => {
    expect(suggestionVisible(EMPTY_SUGGESTION)).toBe(false);
    expect(suggestionVisible(generated)).toBe(false);
    expect(suggestionVisible({ status: "shown", text: "x", shownAt: 1 })).toBe(true);
    expect(suggestionVisible({ status: "accepted", text: "x", shownAt: 1, acceptedAt: 2 })).toBe(true);
    expect(suggestionText(EMPTY_SUGGESTION)).toBeNull();
    expect(suggestionText(generated)).toBe("run the tests");
  });
  it("`markShown` stamps once and is idempotent on an already-shown suggestion", () => {
    const shown = markSuggestionShown(generated, 100);
    expect(shown).toEqual({ status: "shown", text: "run the tests", shownAt: 100 });
    expect(markSuggestionShown(shown, 200)).toBe(shown);                    // same object: no re-stamp
    expect(markSuggestionShown(EMPTY_SUGGESTION, 100)).toBe(EMPTY_SUGGESTION);
  });
  it("`markAccepted` stamps shown → accepted and is a NO-OP for empty/generated", () => {
    const shown = markSuggestionShown(generated, 100);
    expect(markSuggestionAccepted(shown, 250)).toEqual({ status: "accepted", text: "run the tests", shownAt: 100, acceptedAt: 250 });
    expect(markSuggestionAccepted(EMPTY_SUGGESTION, 250)).toBe(EMPTY_SUGGESTION);
    expect(markSuggestionAccepted(generated, 250)).toBe(generated);
  });
  it("render step: a showable `generated` becomes `shown`", () => {
    const step = suggestionRenderStep(generated, { canShow: true, now: 7 });
    expect(step.next).toEqual({ status: "shown", text: "run the tests", shownAt: 7 });
    expect(step.discarded).toBeUndefined();
  });
  it("render step: a `generated` that CANNOT be shown is discarded as `timing` (L495704)", () => {
    const step = suggestionRenderStep(generated, { canShow: false, now: 7 });
    expect(step.next).toBe(EMPTY_SUGGESTION);
    expect(step.discarded).toBe("timing");
  });
  it("render step: a `shown` suggestion SURVIVES the buffer going non-empty (only `generated` times out)", () => {
    const shown = markSuggestionShown(generated, 100);
    expect(suggestionRenderStep(shown, { canShow: false, now: 7 }).next).toBe(shown);
    expect(suggestionRenderStep(shown, { canShow: false, now: 7 }).discarded).toBeUndefined();
  });
  it("render step: `empty` is inert in both directions", () => {
    expect(suggestionRenderStep(EMPTY_SUGGESTION, { canShow: true, now: 7 }).next).toBe(EMPTY_SUGGESTION);
    expect(suggestionRenderStep(EMPTY_SUGGESTION, { canShow: false, now: 7 }).next).toBe(EMPTY_SUGGESTION);
  });
});

