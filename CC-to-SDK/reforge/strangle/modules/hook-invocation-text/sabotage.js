// SABOTAGE LAYER (§2.5).
//
// THE TWIN RETURNS THE HOOK'S KIND for every arm, which is the misreading the
// function's own shape invites: two of its seven arms DO return their own type
// name, and a reader who generalises from those concludes the projection is
// "what kind of hook is this" rather than "what will it run".
//
// It is also the loud direction, which the obvious alternative is not. Dropping
// the `args` join — the simplification the optional field suggests — is INERT on
// this corpus, because none of the eleven command hooks in `w5/scenarios.ts`
// declares args, so both bodies return the bare command. A twin that can only be
// seen on an input the corpus never produces proves nothing, which is the shape
// C9 was corrected for when five of its twins were measured inert. This one
// changes the string the executor runs.
export function hookInvocationText(hook) {
  return hook.type;
}
